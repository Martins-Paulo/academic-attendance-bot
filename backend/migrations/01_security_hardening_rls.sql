-- ------------------------------------------------------------------------------
-- 1. ESTRUTURA BASE DAS TABELAS (DDL IDEMPOTENTE)
-- ------------------------------------------------------------------------------

-- Tabela de Estudantes
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    email TEXT UNIQUE,
    course TEXT DEFAULT 'Engenharia de Software',
    semester INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- Tabela de Disciplinas / Matérias
CREATE TABLE IF NOT EXISTS public.subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    code TEXT NOT NULL,
    total_classes INTEGER NOT NULL DEFAULT 64,
    max_absences INTEGER NOT NULL DEFAULT 16,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- Tabela de Frequência / Presenças e Faltas
CREATE TABLE IF NOT EXISTS public.attendances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    subject_id BIGINT REFERENCES public.subjects(id) ON DELETE CASCADE,
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    status TEXT NOT NULL DEFAULT 'present',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- Tabela de Critérios e Avaliações
CREATE TABLE IF NOT EXISTS public.subject_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT REFERENCES public.subjects(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'exam',
    weight NUMERIC(5,2) NOT NULL DEFAULT 10.00,
    max_score NUMERIC(5,2) DEFAULT 10.00,
    score NUMERIC(5,2) DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- Tabela de Entregas e Eventos Acadêmicos
CREATE TABLE IF NOT EXISTS public.academic_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES public.students(id) ON DELETE CASCADE,
    subject_id BIGINT REFERENCES public.subjects(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    event_date DATE NOT NULL,
    event_time TIME DEFAULT NULL,
    type TEXT NOT NULL DEFAULT 'Trabalho',
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

