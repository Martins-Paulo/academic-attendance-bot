-- ------------------------------------------------------------------------------
-- 3. ÍNDICES DE PERFORMANCE E INTEGRIDADE
-- ------------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_subjects_student ON public.subjects(student_id);
CREATE INDEX IF NOT EXISTS idx_attendances_student ON public.attendances(student_id);
CREATE INDEX IF NOT EXISTS idx_attendances_subject ON public.attendances(subject_id);
CREATE INDEX IF NOT EXISTS idx_subject_evaluations_subject ON public.subject_evaluations(subject_id);
CREATE INDEX IF NOT EXISTS idx_academic_events_student ON public.academic_events(student_id);
CREATE INDEX IF NOT EXISTS idx_academic_events_subject ON public.academic_events(subject_id);

-- ------------------------------------------------------------------------------
-- 4. RESTRIÇÕES DE INTEGRIDADE (CHECK CONSTRAINTS)
-- ------------------------------------------------------------------------------

-- Status de Frequência estrito
ALTER TABLE public.attendances DROP CONSTRAINT IF EXISTS chk_attendance_status;
ALTER TABLE public.attendances ADD CONSTRAINT chk_attendance_status 
    CHECK (status IN ('present', 'absence', 'justified', 'cancelled'));

-- Notas de Avaliações no intervalo [0.00, 10.00]
ALTER TABLE public.subject_evaluations DROP CONSTRAINT IF EXISTS chk_evaluation_score_range;
ALTER TABLE public.subject_evaluations ADD CONSTRAINT chk_evaluation_score_range
    CHECK (score IS NULL OR (score >= 0.00 AND score <= 10.00));

-- Pesos de Avaliações no intervalo [0.00, 100.00]
ALTER TABLE public.subject_evaluations DROP CONSTRAINT IF EXISTS chk_evaluation_weight_range;
ALTER TABLE public.subject_evaluations ADD CONSTRAINT chk_evaluation_weight_range
    CHECK (weight >= 0.00 AND weight <= 100.00);

-- Limite de faltas não pode exceder total de aulas
ALTER TABLE public.subjects DROP CONSTRAINT IF EXISTS chk_subjects_classes_limit;
ALTER TABLE public.subjects ADD CONSTRAINT chk_subjects_classes_limit
    CHECK (max_absences <= total_classes AND total_classes > 0 AND max_absences >= 0);

-- ------------------------------------------------------------------------------
-- 5. HABILITAÇÃO DO ROW LEVEL SECURITY (RLS)
-- ------------------------------------------------------------------------------

ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subjects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendances ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.subject_evaluations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.academic_events ENABLE ROW LEVEL SECURITY;

-- ------------------------------------------------------------------------------
-- 6. POLÍTICAS DE RLS (MODO DESENVOLVIMENTO VS MODO PRODUÇÃO)
-- ------------------------------------------------------------------------------

-- Limpeza de políticas anteriores para evitar duplicidade
DROP POLICY IF EXISTS "students_policy" ON public.students;
DROP POLICY IF EXISTS "subjects_policy" ON public.subjects;
DROP POLICY IF EXISTS "attendances_policy" ON public.attendances;
DROP POLICY IF EXISTS "evaluations_policy" ON public.subject_evaluations;
DROP POLICY IF EXISTS "events_policy" ON public.academic_events;

